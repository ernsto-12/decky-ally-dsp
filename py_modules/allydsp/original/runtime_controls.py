AO_KEYS = tuple("audio-optimizer-bands/ch_%02d" % channel for channel in range(10))
REGULATOR_KEYS = tuple("regulator-tuning/" + name for name in
                       ("threshold_low", "threshold_high", "isolated_band"))
FIELD_NAMES = frozenset(name for _, name, kind in RUNTIME_SLOTS
                        if name is not None and kind not in ("channels", "regulator")) | frozenset(AO_KEYS + REGULATOR_KEYS)


def _integer(value, label):
    if isinstance(value, bool) or not isinstance(value, int) or not -(2 ** 31) <= value < 2 ** 31:
        raise ValueError(label + " must be a signed 32-bit integer")
    return value


def _boolean(value, label):
    if type(value) not in (int, bool) or value not in (0, 1):
        raise ValueError(label + " must be a boolean or integer 0/1")
    return int(value)


def _vector(value, label, length=None, maximum=80):
    if not isinstance(value, (tuple, list)) or not 1 <= len(value) <= maximum or (length is not None and len(value) != length):
        raise ValueError(label + " has an invalid vector length")
    return [_integer(item, label) for item in value]


def encode_runtime(fields):
    """Encode allowlisted official CP fields; absent fields stay unspecified.

    Vectors use an explicit private ``_band-frequencies`` list (1..20 centres,
    strictly increasing, 20..20000 Hz). PO's schema is retained for byte-exact
    replay of official zero values; this does not make PO a supported effect.
    """
    if not isinstance(fields, dict) or any(not isinstance(key, str) for key in fields):
        raise ValueError("Runtime fields must be a string-keyed object")
    unknown = set(fields) - FIELD_NAMES - {"_band-frequencies"}
    if unknown:
        raise ValueError("Unsupported original runtime field: " + sorted(unknown)[0])
    frequencies = None
    band_fields = {"graphic-equalizer-bands", "ieq-bands-set", *AO_KEYS, *REGULATOR_KEYS}
    if set(fields) & band_fields:
        frequencies = _vector(fields.get("_band-frequencies"), "Band frequencies", maximum=20)
        if frequencies != sorted(set(frequencies)) or not all(20 <= value <= 20000 for value in frequencies):
            raise ValueError("Band frequencies must be strictly increasing within 20..20000 Hz")
    elif "_band-frequencies" in fields:
        _vector(fields["_band-frequencies"], "Band frequencies", maximum=20)
    out = bytearray()

    def ints(values):
        out.extend(struct.pack("<" + "i" * len(values), *values))

    for _, name, kind in RUNTIME_SLOTS:
        present = name in fields if name else False
        if kind == "channels":
            present = any(key in fields for key in AO_KEYS)
        elif kind == "regulator":
            present = any(key in fields for key in REGULATOR_KEYS)
        out.append(int(present))
        if not present:
            continue
        if kind == "bool":
            out.append(_boolean(fields[name], name))
        elif kind == "int":
            ints([_integer(fields[name], name)])
        elif kind in ("matrix", "pair", "triple", "eight"):
            length = {"matrix": None, "pair": 2, "triple": 3, "eight": 8}[kind]
            values = _vector(fields[name], name, length, maximum=80 if kind == "matrix" else 8)
            if kind in ("matrix", "triple"):
                ints([len(values)])
            ints(values)
        elif kind == "bands":
            gains = _vector(fields[name], name, len(frequencies), maximum=20)
            ints([len(frequencies)])
            for frequency, gain in zip(frequencies, gains):
                ints([frequency, gain])
        elif kind == "channels":
            ints([len(frequencies), *frequencies])
            for key in AO_KEYS:
                out.append(int(key in fields))
                if key in fields:
                    ints(_vector(fields[key], key, len(frequencies), maximum=20))
        elif kind == "regulator":
            if not all(key in fields for key in REGULATOR_KEYS):
                raise ValueError("Regulator tuning requires low, high and isolated vectors")
            lows, highs, isolated = (_vector(fields[key], key, len(frequencies), maximum=20)
                                     for key in REGULATOR_KEYS)
            ints([len(frequencies)])
            for frequency, low, high, is_isolated in zip(frequencies, lows, highs, isolated):
                ints([frequency, low, high])
                out.append(_boolean(is_isolated, "Regulator isolated band"))
    return bytes(out)


CONTROL_FIELDS = {
    "eqEnabled": ("graphic-equalizer-enable", "bool", 0, 1),
    "ieqEnabled": ("ieq-enable", "bool", 0, 1),
    "ieqAmount": ("ieq-amount", "int", 0, 16),
    "dialogEnabled": ("dialog-enhancer-enable", "bool", 0, 1),
    "dialogAmount": ("dialog-enhancer-amount", "int", 0, 16),
    "volumeLevelerEnabled": ("volume-leveler-enable", "bool", 0, 1),
    "volumeLevelerAmount": ("volume-leveler-amount", "int", 0, 10),
}


def normalize_controls(raw):
    """Validate partial user overrides. Empty overrides preserve OEM defaults."""
    if not isinstance(raw, dict) or set(raw) - set(CONTROL_FIELDS) - {"eqBandsDb", "spatialEnabled"}:
        raise ValueError("Unknown original user control")
    result = {}
    for key, value in raw.items():
        if key == "spatialEnabled":
            result[key] = bool(_boolean(value, key))
            continue
        if key == "eqBandsDb":
            if not isinstance(value, (list, tuple)) or len(value) != 20:
                raise ValueError("Original EQ requires exactly 20 band values")
            bands = []
            for item in value:
                if isinstance(item, bool) or not isinstance(item, (float, int)) or not math.isfinite(item) or not -12 <= item <= 12 or item * 2 != round(item * 2):
                    raise ValueError("EQ gain must be -12..12 dB in 0.5 dB steps")
                bands.append(float(item))
            result[key] = bands
            continue
        _, kind, low, high = CONTROL_FIELDS[key]
        if kind == "bool":
            result[key] = bool(_boolean(value, key))
        else:
            value = _integer(value, key)
            if not low <= value <= high:
                raise ValueError(key + " is outside the supported range")
            result[key] = value
    return result


def controls_to_fields(controls, base_fields, *, route="speakers"):
    """Overlay partial user controls on a private profile's official fields."""
    if route not in ("speakers", "headphones"):
        raise ValueError("Unknown original output route")
    fields = dict(base_fields)
    for key, value in normalize_controls(controls).items():
        if key == "eqBandsDb":
            # Original DAP GEQ band targets are sixteenths of one decibel.
            fields["graphic-equalizer-bands"] = [round(item * 16) for item in value]
        elif key == "spatialEnabled":
            fields["output-mode/processing_mode"] = (11 if route == "speakers" else 9) if value else 1
        else:
            fields[CONTROL_FIELDS[key][0]] = value
    return fields


def fields_to_controls(base_fields):
    """Expose only known profile values; missing input is not a guessed default."""
    result = {}
    for key, (field, kind, _, _) in CONTROL_FIELDS.items():
        if field in base_fields:
            result[key] = bool(_boolean(base_fields[field], field)) if kind == "bool" else _integer(base_fields[field], field)
    if "graphic-equalizer-bands" in base_fields:
        result["eqBandsDb"] = [value / 16 for value in _vector(
            base_fields["graphic-equalizer-bands"], "Graphic EQ", 20, maximum=20)]
    if "output-mode/processing_mode" in base_fields:
        result["spatialEnabled"] = base_fields["output-mode/processing_mode"] in (9, 11)
    return result
