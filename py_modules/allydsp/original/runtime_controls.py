"""Bounded, packed ASAR runtime input for the pinned original receiver.

This is a transport encoder, not a DSP implementation. Its ordering and scalar
widths follow DAX3API 3.30902.922.0 RuntimeParams::Serialize (RVA 0x192c30).
The generated bytes are delivered through the original property notification;
no original DSP state is written. Tuning values and band centres come from the
user's private profile catalog, rather than a public copy of OEM tuning.
"""
from __future__ import annotations

import math
import struct


